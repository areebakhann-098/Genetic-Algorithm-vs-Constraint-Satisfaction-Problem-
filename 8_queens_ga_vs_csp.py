import time
import pandas as pd
import matplotlib.pyplot as plt

def improved_csp_fc_mrv_lcv(n, time_limit=5):
    start_time = time.perf_counter()
    nodes = 0

    # Each row initially allows every column
    domains = {row: set(range(n)) for row in range(n)}
    assignment = {}

    def backtrack(current_domains):
        nonlocal nodes

        if time.perf_counter() - start_time > time_limit:
            raise TimeoutError

        nodes += 1

        if len(assignment) == n:
            return True

        # MRV: select the unassigned row with the fewest legal columns
        unassigned = [
            row for row in range(n)
            if row not in assignment
        ]

        row = min(unassigned, key=lambda r: len(current_domains[r]))

        if not current_domains[row]:
            return False

        # LCV: try the column that eliminates the fewest options
        def lcv_score(col):
            eliminated = 0

            for other_row in unassigned:
                if other_row == row:
                    continue

                for other_col in current_domains[other_row]:
                    if (
                        other_col == col
                        or abs(other_col - col) == abs(other_row - row)
                    ):
                        eliminated += 1

            return eliminated

        ordered_columns = sorted(
            current_domains[row],
            key=lcv_score
        )

        for col in ordered_columns:
            assignment[row] = col

            # Forward Checking: update domains of future rows
            new_domains = {
                r: set(values)
                for r, values in current_domains.items()
            }

            valid = True

            for other_row in unassigned:
                if other_row == row:
                    continue

                new_domains[other_row] = {
                    other_col
                    for other_col in new_domains[other_row]
                    if (
                        other_col != col
                        and abs(other_col - col)
                        != abs(other_row - row)
                    )
                }

                # Empty domain means this branch cannot work
                if not new_domains[other_row]:
                    valid = False
                    break

            if valid and backtrack(new_domains):
                return True

            del assignment[row]

        return False

    try:
        success = backtrack(domains)
        status = "Solved" if success else "No solution"
    except TimeoutError:
        success = False
        status = "Timeout"

    runtime = time.perf_counter() - start_time

    solution = (
        [assignment[r] for r in range(n)]
        if success else None
    )

    return {
        "algorithm": "Improved CSP (FC+MRV+LCV)",
        "N": n,
        "success": success,
        "status": status,
        "runtime_sec": runtime,
        "effort": nodes,
        "solution": solution
    }


